-- ===== Criação do banco =====

SET NAMES utf8mb4;
SET lc_time_names = 'pt_BR';

CREATE DATABASE IF NOT EXISTS FICHA_RPG
    CHARACTER SET utf8mb4
    COLLATE utf8mb4_unicode_ci;

USE FICHA_RPG;

-- ===== USUARIO =====
CREATE TABLE IF NOT EXISTS USUARIO (
    COD_USUARIO INT AUTO_INCREMENT PRIMARY KEY,
    NOME_USUARIO VARCHAR(100) NOT NULL,
    EMAIL VARCHAR(150) NOT NULL UNIQUE,
    SENHA_HASH VARCHAR(255) NOT NULL,
    DATA_CADASTRO DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

-- ===== PERSONAGEM =====
CREATE TABLE IF NOT EXISTS PERSONAGEM (
    COD_PERSONAGEM INT AUTO_INCREMENT PRIMARY KEY,
    NOME_PERSONAGEM VARCHAR(150) NOT NULL,
    NOME_JOGADOR VARCHAR(150) NOT NULL,
    IMAGEM VARCHAR(255) DEFAULT NULL,
    RACA VARCHAR(100) NOT NULL,
    CLASSE VARCHAR(100) NOT NULL,
    NIVEL INT NOT NULL DEFAULT 1,
    ANTECEDENTE VARCHAR(100) DEFAULT NULL,
    ALINHAMENTO VARCHAR(100) DEFAULT NULL,
    EXP INT NOT NULL DEFAULT 0,

    ATRIBUTO_FOR TINYINT UNSIGNED NOT NULL DEFAULT 10,
    ATRIBUTO_DES TINYINT UNSIGNED NOT NULL DEFAULT 10,
    ATRIBUTO_CONST TINYINT UNSIGNED NOT NULL DEFAULT 10,
    ATRIBUTO_INT TINYINT UNSIGNED NOT NULL DEFAULT 10,
    ATRIBUTO_SAB TINYINT UNSIGNED NOT NULL DEFAULT 10,
    ATRIBUTO_CAR TINYINT UNSIGNED NOT NULL DEFAULT 10,
    PERICIA_ACROBACIA TINYINT UNSIGNED NOT NULL DEFAULT 0,
    PERICIA_ADESTRAR_ANIMAIS TINYINT UNSIGNED NOT NULL DEFAULT 0,
    PERICIA_ARCANISMO TINYINT UNSIGNED NOT NULL DEFAULT 0,
    PERICIA_ATLETISMO TINYINT UNSIGNED NOT NULL DEFAULT 0,
    PERICIA_ATUACAO TINYINT UNSIGNED NOT NULL DEFAULT 0,
    PERICIA_ENGANACAO TINYINT UNSIGNED NOT NULL DEFAULT 0,
    PERICIA_FURTIVIDADE TINYINT UNSIGNED NOT NULL DEFAULT 0,
    PERICIA_HISTORIA TINYINT UNSIGNED NOT NULL DEFAULT 0,
    PERICIA_INTIMIDACAO TINYINT UNSIGNED NOT NULL DEFAULT 0,
    PERICIA_INTUICAO TINYINT UNSIGNED NOT NULL DEFAULT 0,
    PERICIA_INVESTIGACAO TINYINT UNSIGNED NOT NULL DEFAULT 0,
    PERICIA_MEDICINA TINYINT UNSIGNED NOT NULL DEFAULT 0,
    PERICIA_NATUREZA TINYINT UNSIGNED NOT NULL DEFAULT 0,
    PERICIA_PERCEPCAO TINYINT UNSIGNED NOT NULL DEFAULT 0,
    PERICIA_PERSUASAO TINYINT UNSIGNED NOT NULL DEFAULT 0,
    PERICIA_PRESTIDIGITACAO TINYINT UNSIGNED NOT NULL DEFAULT 0,
    PERICIA_RELIGIAO TINYINT UNSIGNED NOT NULL DEFAULT 0,
    PERICIA_SOBREVIVENCIA TINYINT UNSIGNED NOT NULL DEFAULT 0,

    PV INT NOT NULL DEFAULT 10,
    PV_MAXIMO INT NOT NULL DEFAULT 10,
    CA INT NOT NULL DEFAULT 10,
    ATAQUES TEXT DEFAULT NULL,
    INVENTARIO TEXT DEFAULT NULL,
    PODER_RACA TEXT DEFAULT NULL,
    PODER_CLASSE TEXT DEFAULT NULL,
    RECURSOS_CLASSE TEXT DEFAULT NULL,
    TRACOS TEXT DEFAULT NULL,
    ESPACOS_MAGIA TEXT DEFAULT NULL,
    MAGIAS TEXT DEFAULT NULL,

    COD_USUARIO_FK INT NOT NULL,
    DATA_CRIACAO DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    DATA_ATUALIZACAO DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

    CONSTRAINT FK_PERSONAGEM_USUARIO
        FOREIGN KEY (COD_USUARIO_FK) REFERENCES USUARIO(COD_USUARIO)
        ON DELETE CASCADE,
    INDEX IDX_PERSONAGEM_USUARIO (COD_USUARIO_FK),
    INDEX IDX_PERSONAGEM_NOME (NOME_PERSONAGEM)
) ENGINE=InnoDB;

-- ===== HISTORIA_PERSONAGEM =====
CREATE TABLE IF NOT EXISTS HISTORIA_PERSONAGEM (
    COD_PERSONAGEM_FK INT PRIMARY KEY,
    HISTORIA LONGTEXT DEFAULT NULL,
    TRACOS_PERSONALIDADE TEXT DEFAULT NULL,
    IDEAIS TEXT DEFAULT NULL,
    VINCULOS TEXT DEFAULT NULL,
    DEFEITOS TEXT DEFAULT NULL,
    CONSTRAINT FK_HISTORIA_PERSONAGEM
        FOREIGN KEY (COD_PERSONAGEM_FK) REFERENCES PERSONAGEM(COD_PERSONAGEM)
        ON DELETE CASCADE
) ENGINE=InnoDB;

-- ===== CRIATURA =====
CREATE TABLE IF NOT EXISTS CRIATURA (
    COD_CRIATURA INT AUTO_INCREMENT PRIMARY KEY,
    NOME_CRIATURA VARCHAR(150) NOT NULL,
    TIPO VARCHAR(150) NOT NULL,
    TAMANHO VARCHAR(50) NOT NULL,
    ND DECIMAL(5,3) NOT NULL DEFAULT 0,

    ATRIBUTO_FOR TINYINT UNSIGNED NOT NULL DEFAULT 10,
    ATRIBUTO_DES TINYINT UNSIGNED NOT NULL DEFAULT 10,
    ATRIBUTO_CONST TINYINT UNSIGNED NOT NULL DEFAULT 10,
    ATRIBUTO_INT TINYINT UNSIGNED NOT NULL DEFAULT 10,
    ATRIBUTO_SAB TINYINT UNSIGNED NOT NULL DEFAULT 10,
    ATRIBUTO_CAR TINYINT UNSIGNED NOT NULL DEFAULT 10,

    PV INT NOT NULL DEFAULT 1,
    PV_ATUAL INT NOT NULL DEFAULT 1,
    CA INT NOT NULL DEFAULT 10,
    DESCRICAO TEXT DEFAULT NULL,
    ATAQUES TEXT DEFAULT NULL,
    INVENTARIO TEXT DEFAULT NULL,
    PODERES TEXT DEFAULT NULL,
    MAGIAS TEXT DEFAULT NULL,
    IMAGEM VARCHAR(255) DEFAULT NULL,
    COD_USUARIO_FK INT DEFAULT NULL,
    DATA_CRIACAO DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    DATA_ATUALIZACAO DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,

    CONSTRAINT FK_CRIATURA_USUARIO
        FOREIGN KEY (COD_USUARIO_FK) REFERENCES USUARIO(COD_USUARIO)
        ON DELETE CASCADE,
    INDEX IDX_CRIATURA_USUARIO (COD_USUARIO_FK),
    INDEX IDX_CRIATURA_NOME (NOME_CRIATURA)
) ENGINE=InnoDB;

-- ===== DOCUMENTACAO =====
CREATE TABLE IF NOT EXISTS DOCUMENTACAO (
    COD_DOCUMENTACAO INT AUTO_INCREMENT PRIMARY KEY,
    TITULO VARCHAR(150) NOT NULL,
    CATEGORIA VARCHAR(50) NOT NULL DEFAULT 'Anotações',
    RESUMO VARCHAR(255) DEFAULT NULL,
    CONTEUDO LONGTEXT NOT NULL,
    DATA_CRIACAO DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    DATA_ATUALIZACAO DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    COD_USUARIO_FK INT NOT NULL,

    CONSTRAINT FK_DOCUMENTACAO_USUARIO
        FOREIGN KEY (COD_USUARIO_FK) REFERENCES USUARIO(COD_USUARIO)
        ON DELETE CASCADE,
    INDEX IDX_DOCUMENTACAO_USUARIO (COD_USUARIO_FK),
    INDEX IDX_DOCUMENTACAO_CATEGORIA (CATEGORIA)
) ENGINE=InnoDB;
